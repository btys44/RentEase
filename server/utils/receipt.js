const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

/**
 * Generates a PDF rent receipt and saves it to /uploads/receipts.
 * Returns the relative URL that can be served via the /uploads static route.
 */
function generateReceipt({ payment, tenant, unit, property, landlordName }) {
  return new Promise((resolve, reject) => {
    const receiptNumber = `RCPT-${payment.id.toString().padStart(6, '0')}`;
    const uploadDir = path.join(
      __dirname,
      '..',
      process.env.UPLOAD_DIR || 'uploads',
      'receipts'
    );
    if (!fs.existsSync(uploadDir)) fs.mkdirSync(uploadDir, { recursive: true });

    const fileName = `${receiptNumber}.pdf`;
    const filePath = path.join(uploadDir, fileName);
    const doc = new PDFDocument({ size: 'A5', margin: 40 });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    // --- Header ---
    doc
      .rect(0, 0, doc.page.width, 90)
      .fill('#15803d');

    doc
      .fillColor('#ffffff')
      .fontSize(10)
      .text('[ LOGO ]', 40, 20, { width: 60 });

    doc
      .fillColor('#ffffff')
      .fontSize(20)
      .font('Helvetica-Bold')
      .text('RentEase Kenya', 40, 38);

    doc
      .fontSize(10)
      .font('Helvetica')
      .fillColor('#dcfce7')
      .text('Rental Property Management System', 40, 64);

    doc.fillColor('#000000');

    // --- Receipt meta ---
    let y = 110;
    doc.fontSize(14).font('Helvetica-Bold').text('OFFICIAL RENT RECEIPT', 40, y);
    y += 24;

    doc.fontSize(10).font('Helvetica');
    doc.text(`Receipt No: ${receiptNumber}`, 40, y);
    doc.text(`Date: ${new Date(payment.createdAt).toLocaleDateString('en-KE')}`, 300, y);
    y += 30;

    // --- Divider ---
    doc.moveTo(40, y).lineTo(doc.page.width - 40, y).strokeColor('#e5e7eb').stroke();
    y += 16;

    const row = (label, value) => {
      doc.font('Helvetica-Bold').text(label, 40, y, { continued: false });
      doc.font('Helvetica').text(value, 200, y);
      y += 20;
    };

    row('Tenant Name:', tenant.name);
    row('Property:', property.name);
    row('Unit Number:', unit.unitNumber);
    row('Amount Paid:', `KES ${Number(payment.amount).toLocaleString('en-KE')}`);
    row('M-Pesa Reference:', payment.mpesaRef || 'N/A');
    row('Month Paid For:', `${monthName(payment.month)} ${payment.year}`);
    row('Payment Status:', payment.status);

    y += 20;
    doc.moveTo(40, y).lineTo(doc.page.width - 40, y).strokeColor('#e5e7eb').stroke();
    y += 30;

    // --- Signature ---
    doc.font('Helvetica').text(`Landlord: ${landlordName}`, 40, y);
    y += 30;
    doc.text('Signature: ____________________________', 40, y);
    y += 40;

    // --- Footer ---
    doc
      .fontSize(8)
      .fillColor('#6b7280')
      .text('This is an official receipt generated by RentEase Kenya', 40, doc.page.height - 60, {
        width: doc.page.width - 80,
        align: 'center',
      });

    doc.end();

    stream.on('finish', () => {
      resolve(`/uploads/receipts/${fileName}`);
    });
    stream.on('error', reject);
  });
}

function monthName(monthNum) {
  const months = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December',
  ];
  return months[monthNum - 1] || monthNum;
}

module.exports = { generateReceipt };
